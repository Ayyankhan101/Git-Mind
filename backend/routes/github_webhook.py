"""GitHub App webhook receiver — handles push, pull_request, and installation events."""

import asyncio
import hashlib
import hmac
import json
import os

import structlog
from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

logger = structlog.get_logger(__name__)
router = APIRouter()


def verify_hmac_signature(payload: bytes, signature_header: str, secret: str) -> bool:
    """Verify the x-hub-signature-256 HMAC header against the webhook secret."""
    if not signature_header or not signature_header.startswith("sha256="):
        return False
    expected = "sha256=" + hmac.new(secret.encode("utf-8"), payload, hashlib.sha256).hexdigest()
    return hmac.compare_digest(expected, signature_header)


async def _handle_pr_event(payload: dict):
    """Handle pull_request events — trigger AI review and post comment."""
    action = payload.get("action")
    if action not in ("opened", "synchronize", "reopened"):
        return

    pr = payload.get("pull_request", {})
    pr_url = pr.get("html_url", "")
    pr_number = pr.get("number", 0)
    repo_data = payload.get("repository", {})
    owner = repo_data.get("owner", {}).get("login", "")
    repo = repo_data.get("name", "")
    head_sha = pr.get("head", {}).get("sha", "")

    if not pr_url or not owner or not repo:
        logger.warning("Incomplete PR webhook payload", action=action)
        return

    logger.info(
        "GitHub webhook: PR event",
        action=action,
        repo=f"{owner}/{repo}",
        pr=pr_number,
        sha=head_sha[:8],
    )

    # Run PR review asynchronously to avoid blocking the webhook response
    asyncio.create_task(_run_pr_review_and_comment(owner, repo, pr_number, pr_url))


async def _run_pr_review_and_comment(owner: str, repo: str, pr_number: int, pr_url: str):
    """Run AI PR review and post results as a PR comment."""
    try:
        from agents.pr_review import run_pr_review
        from services.github_app import get_installation_token, post_comment

        token = await get_installation_token()
        review = await asyncio.to_thread(run_pr_review, pr_url, token)
        if not review:
            return

        body = (
            f"## GitMind PR Review\n\n{review}\n\n---\n"
            f"*Auto-generated by [GitMind](https://github.com) "
            f"— AI-powered code analysis.*"
        )
        await post_comment(owner, repo, pr_number, body)
        logger.info("PR review comment posted", repo=f"{owner}/{repo}", pr=pr_number)

    except Exception as exc:
        logger.error("Failed to post PR review", error=str(exc)[:300], pr=pr_number, repo=f"{owner}/{repo}")


async def _handle_push_event(payload: dict):
    """Handle push events — optionally trigger monitoring checks."""
    ref = payload.get("ref", "")
    repo_data = payload.get("repository", {})
    owner = repo_data.get("owner", {}).get("login", "")
    repo = repo_data.get("name", "")
    head_commit = payload.get("head_commit", {})
    sha = head_commit.get("id", "") if head_commit else ""

    logger.info(
        "GitHub webhook: push event",
        ref=ref,
        repo=f"{owner}/{repo}",
        sha=sha[:8] if sha else "unknown",
    )

    # Push events could trigger monitoring checks if the repo is being monitored
    # This is handled by the existing monitoring loop, but webhooks give us real-time updates
    if ref in ("refs/heads/main", "refs/heads/master"):
        repo_url = f"https://github.com/{owner}/{repo}"
        try:
            from sqlalchemy import select

            from models.db import MonitoredRepo
            from services.database import async_session_factory

            async with async_session_factory() as session:
                result = await session.execute(select(MonitoredRepo).where(MonitoredRepo.repo_url == repo_url))
                monitored = result.scalars().all()
                if monitored:
                    logger.info("Webhook: triggering monitoring check for", repo=repo_url)
                    # The monitoring loop will pick this up on next interval
                    # But we could trigger it immediately here if needed
        except Exception as exc:
            logger.warning("Webhook push handler error", error=str(exc)[:200])


async def _handle_installation_event(payload: dict):
    """Handle GitHub App installation lifecycle events."""
    action = payload.get("action")
    installation = payload.get("installation", {})
    account = installation.get("account", {})

    logger.info(
        "GitHub webhook: installation event",
        action=action,
        account=account.get("login", "unknown"),
        installation_id=installation.get("id"),
    )

    if action == "created":
        logger.info(
            "GitHub App installed",
            account=account.get("login"),
            installation_id=installation.get("id"),
        )
    elif action == "deleted":
        logger.info(
            "GitHub App uninstalled",
            account=account.get("login"),
            installation_id=installation.get("id"),
        )
    elif action == "suspended":
        logger.warning(
            "GitHub App suspended",
            account=account.get("login"),
            installation_id=installation.get("id"),
        )


@router.post("/github/webhook")
async def github_webhook(request: Request):
    """Receive and process GitHub webhook events."""
    # Rate limit by IP to prevent abuse
    client_ip = request.client.host if request.client else "unknown"
    from services.rate_limit_response import rate_limit_response
    from services.rate_limiter import check_rate_limit

    allowed, _, _ = await check_rate_limit("webhook", client_ip)
    if not allowed:
        return await rate_limit_response("webhook", client_ip)

    secret = os.getenv("GITHUB_APP_WEBHOOK_SECRET")

    # Read raw body for HMAC verification
    body = await request.body()

    # Verify signature if secret is configured
    if secret:
        signature = request.headers.get("x-hub-signature-256", "")
        if not verify_hmac_signature(body, signature, secret):
            logger.warning("GitHub webhook: invalid HMAC signature")
            return JSONResponse(status_code=401, content={"error": "Invalid signature"})

    # Parse payload
    try:
        payload = json.loads(body)
    except json.JSONDecodeError:
        return JSONResponse(status_code=400, content={"error": "Invalid JSON"})

    github_event = request.headers.get("x-github-event", "")
    delivery_id = request.headers.get("x-github-delivery", "")

    logger.info(
        "GitHub webhook received",
        github_event=github_event,
        delivery_id=delivery_id,
        action=payload.get("action", "N/A"),
    )

    try:
        if github_event == "pull_request":
            await _handle_pr_event(payload)
        elif github_event == "push":
            await _handle_push_event(payload)
        elif github_event == "installation":
            await _handle_installation_event(payload)
        elif github_event == "ping":
            logger.info("GitHub webhook: ping received")
        else:
            logger.debug("GitHub webhook: unhandled event type", github_event=github_event)
    except Exception as exc:
        logger.error("GitHub webhook handler error", github_event=github_event, error=str(exc)[:200])
        return JSONResponse(status_code=500, content={"error": "Handler error"})

    return {"ok": True}
